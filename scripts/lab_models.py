"""Generate, configure and inspect the skill's native pedestrian lab models."""

import argparse
import csv
from math import isfinite
from pathlib import Path
import re
import sys
from tempfile import NamedTemporaryFile

from lxml import etree as xml


MODEL = "./Model"
MAIN = MODEL + '/ActiveObjectClasses/ActiveObjectClass[Name="Main"]'
EXPERIMENT = MODEL + "/Experiments/SimulationExperiment"
NATIVE_CLASSES = ("PedSource", "PedElevator", "PedGoTo", "PedSink")
CSV_FIELDS = (
    "time_s", "generated", "boarded", "transported", "left", "mean_wait_s",
    "mean_ride_s", "active_waiting", "native_transported",
    "peak_load_a", "peak_load_b", "peak_load_c", "capacity", "rate_per_lane",
)


def read_alp(path):
    if path.suffix.lower() != ".alp":
        raise ValueError("This editor handles single-file .alp models only")
    parser = xml.XMLParser(strip_cdata=False, resolve_entities=False, no_network=True)
    tree = xml.parse(str(path), parser)
    if tree.docinfo.doctype or tree.getroot().tag != "AnyLogicWorkspace":
        raise ValueError("Expected native AnyLogicWorkspace XML without a DTD")
    return tree


def write_alp(tree, path):
    if path.exists():
        raise FileExistsError(f"{path} already exists. Use a new output file.")
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(dir=path.parent, delete=False) as temp:
        temp_path = Path(temp.name)
        tree.write(temp, encoding="UTF-8", xml_declaration=True, pretty_print=True)
    try:
        temp_path.rename(path)
    finally:
        temp_path.unlink(missing_ok=True)


def child(node, tag, value, code=True):
    element = node.find(tag)
    if element is None:
        element = xml.SubElement(node, tag)
    element.text = xml.CDATA(str(value)) if code else str(value)


def remove(node):
    node.getparent().remove(node)


def parameter(block, name):
    return block.find(f'Parameters/Parameter[Name="{name}"]/Value/Code')


def apply_config(tree, capacity=None, rate=None, seed=None):
    main = tree.find(MAIN)
    if main is None or not tree.findtext(MODEL + "/JavaPackageName", "").startswith("anylogic_lab_"):
        raise ValueError("The configure command expects a lab generated by this script")
    if capacity is not None:
        descriptors = main.xpath("./Presentation/Level/Presentation/Elevator/EmbeddedObject")
        if not descriptors:
            raise ValueError("The pedestrian-only model has no elevator capacity")
        for descriptor in descriptors:
            parameter(descriptor, "capacity").text = xml.CDATA(str(capacity))
    if rate is not None:
        code = main.find('Variables/Variable[Name="studentsPerMinutePerLift"]/Properties/InitialValue/Code')
        code.text = xml.CDATA(str(rate))
    if seed is not None:
        child(tree.find(EXPERIMENT), "SeedValue", seed, code=False)


def rename_project(tree, project_name):
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", project_name):
        raise ValueError("Use an ASCII model filename beginning with a letter")
    model = tree.find(MODEL)
    previous = model.findtext("JavaPackageName")
    package = "anylogic_lab_" + project_name.lower()
    for ref in tree.xpath(".//PackageName"):
        if ref.text == previous:
            ref.text = xml.CDATA(package)
    child(model, "Name", project_name)
    child(model, "JavaPackageName", package)
    child(tree.find(EXPERIMENT + "/PresentationProperties"), "Title", project_name)


def metric_code(cars, output):
    if cars:
        car_names = [f"lift{letter}" for letter in "ABC"[:cars]]
        native = " + ".join(f"root.{name}.nTransportedPeds()" for name in car_names)
        sinks = " + ".join(f"root.leaveBuilding{letter}.countPeds()" for letter in "ABC"[:cars])
        sources = " + ".join(f"root.arrivals{letter}.countPeds()" for letter in "ABC"[:cars])
        waiting = "java.util.Arrays.stream(root.waitingByFloor).sum()"
        capacity_checks = "".join(
            f'if (root.{name}.getPeds().size() > root.{name}.getCapacity()) '
            f'throw new IllegalStateException("{name} exceeded capacity at the end of run");\n'
            for name in car_names
        )
        per_car_checks = "".join(
            f'if (root.{name}.nTransportedPeds() == 0) '
            f'throw new IllegalStateException("{name} transported nobody");\n'
            for name in car_names
        )
        outcome_checks = (
            'if (transported <= 0 || transported != nativeTransported || '
            'root.boardedCount < transported || left > transported || activeWaiting < 0) '
            'throw new IllegalStateException("Elevator flow totals are inconsistent");\n'
        )
        capacity = "root.liftA.getCapacity()"
    else:
        native, sinks, sources, waiting = "0", "root.leaveBuildingA.countPeds()", "root.arrivalsA.countPeds()", "0"
        capacity_checks = per_car_checks = outcome_checks = ""
        capacity = "0"
    quoted_path = str(output).replace("\\", "\\\\").replace('"', '\\"')
    columns = ",".join(CSV_FIELDS)
    return f'''
long generated = {sources};
long left = {sinks};
int transported = root.transportedCount;
int nativeTransported = {native};
int activeWaiting = {waiting};
if (left <= 0 || left > generated)
    throw new IllegalStateException("The pedestrian flow did not complete");
{capacity_checks}{per_car_checks}{outcome_checks}
String row = String.format(java.util.Locale.ROOT, "%.3f,%d,%d,%d,%d,%s,%s,%d,%d,%d,%d,%d,%d,%.6f%n",
    getEngine().getTime(), generated, root.boardedCount, transported, left,
    root.boardedCount == 0 ? "" : Double.toString(root.waitSeconds / root.boardedCount),
    transported == 0 ? "" : Double.toString(root.rideSeconds / transported),
    activeWaiting, nativeTransported, root.peakLoadByCar[0], root.peakLoadByCar[1],
    root.peakLoadByCar[2], {capacity}, root.studentsPerMinutePerLift);
java.nio.file.Path output = java.nio.file.Path.of("{quoted_path}");
try {{
    java.nio.file.Files.writeString(output, "{columns}\\n" + row, java.nio.charset.StandardCharsets.UTF_8);
}} catch (java.io.IOException error) {{
    throw new java.io.UncheckedIOException("Cannot write " + output, error);
}}
traceln("Wrote " + output);
'''.strip()


def make_lab(output, cars, capacity, rate, seed, tree):
    rename_project(tree, output.stem)
    main = tree.find(MAIN)
    presentation = main.find("Presentation")
    objects = main.find("EmbeddedObjects")
    links = main.find("Connectors")
    # The seed has three independent connected lanes. Keep an entire lane per car.
    for letter in "ABC"[max(cars, 1):]:
        for block in objects.xpath(f'EmbeddedObject[substring(Name,string-length(Name))="{letter}"]'):
            remove(block)
        for link in links.xpath(f'Connector[starts-with(Name,"link{letter}")]'):
            remove(link)
    for lift in presentation.xpath("./Level/Presentation/Elevator"):
        if lift.findtext("Name")[-1] not in "ABC"[:cars]:
            remove(lift)
    for shape in presentation.xpath('./Level/Presentation/*[starts-with(Name,"shaftBay") or starts-with(Name,"bayLabel")]'):
        if shape.findtext("Name")[-2] not in "ABC"[:cars]:
            remove(shape)
    if cars == 0:
        remove(presentation.find('Level[Name="floor2"]'))
        for button in presentation.xpath('./Level/Presentation/*[starts-with(Name,"floorButton")]'):
            remove(button)
        remove(objects.find('EmbeddedObject[Name="rideA"]'))
        first = links.find('Connector[Name="linkA1"]')
        second = links.find('Connector[Name="linkA2"]')
        first.replace(first.find("SourceEmbeddedObjectReference"), second.find("SourceEmbeddedObjectReference"))
        first.replace(first.find("SourceConnectableItemReference"), second.find("SourceConnectableItemReference"))
        for point in first.findall("Points/Point")[1:]:
            child(point, "X", -200, code=False)
        child(first, "X", 1250, code=False)
        remove(second)
        source = objects.find('EmbeddedObject[Name="arrivalsA"]')
        parameter(source, "locationLine").text = xml.CDATA("entry1")
        remove(parameter(source, "onExit").getparent())
        parameter(objects.find('EmbeddedObject[Name="walkToExitA"]'), "locationLine").text = xml.CDATA("exit1")
        for name in ("floors", "entryLines", "exitLines", "waitingByFloor", "visibleFloor"):
            remove(main.find(f'Variables/Variable[Name="{name}"]'))
        for function in main.findall("Functions/Function"):
            remove(function)
        child(main, "StartupCode", "dashboard.navigateTo();")
        remove(presentation.find('Level[Name="floor1"]/Presentation/Rectangle[Name="lobby1"]'))
        remove(presentation.find('Level[Name="floor1"]/Presentation/Text[Name="lobbyLabel1"]'))

    apply_config(tree, capacity if cars else None, rate, seed)
    child(tree.find(EXPERIMENT), "AfterSimulationRunCode", metric_code(cars, output.with_suffix(".csv")))
    write_alp(tree, output)
    inspect(output)


def inspect(path):
    tree = read_alp(path)
    dups = set()
    ids = set()
    for node in tree.xpath(".//Id"):
        if node.text in ids:
            dups.add(node.text)
        ids.add(node.text)
    if dups:
        raise ValueError(f"Duplicate explicit IDs: {sorted(dups)}")
    for agent in tree.xpath("./Model/ActiveObjectClasses/ActiveObjectClass"):
        level_ids = {level.findtext("Id") for level in agent.findall("Presentation/Level")}
        active_level = agent.findtext("CurrentLevel")
        if active_level and active_level not in level_ids:
            raise ValueError(f'{agent.findtext("Name")}: unresolved CurrentLevel {active_level}')
        flow_names = {block.findtext("Name") for block in agent.findall("EmbeddedObjects/EmbeddedObject")}
        for link in agent.findall("Connectors/Connector"):
            for endpoint in ("Source", "Target"):
                ref = link.findtext(f"{endpoint}EmbeddedObjectReference/ItemName")
                if ref and ref not in flow_names and link.findtext(f"{endpoint}EmbeddedObjectReference/ClassName") == agent.findtext("Name"):
                    raise ValueError(f'{agent.findtext("Name")}: unresolved connector reference {ref}')
    agent_ids = {agent.findtext("Id") for agent in tree.xpath("./Model/ActiveObjectClasses/ActiveObjectClass")}
    for experiment in tree.xpath("./Model/Experiments/*[@ActiveObjectClassId] | ./Model/RunConfiguration[@ActiveObjectClassId]"):
        if experiment.get("ActiveObjectClassId") not in agent_ids:
            raise ValueError("Unresolved experiment root agent ID")
    main = tree.find(MAIN)
    lifts = main.xpath("./Presentation/Level/Presentation/Elevator") if main is not None else []
    capacities = [parameter(lift.find("EmbeddedObject"), "capacity") for lift in lifts]
    capacity_values = [value.text if value is not None else "library default" for value in capacities]
    print(f"{path.name}: ALP {tree.getroot().get('AlpVersion')}, {len(agent_ids)} agent types")
    if main is not None:
        if main.findtext("CurrentLevel"):
            levels = [level.findtext("Name") for level in main.findall("Presentation/Level")]
            print(f"  levels={','.join(levels)}")
        blocks = [block.findtext("ActiveObjectClass/ClassName") for block in main.findall("EmbeddedObjects/EmbeddedObject")]
        print("  " + ", ".join(f"{cls}={blocks.count(cls)}" for cls in NATIVE_CLASSES))
        print(f"  lifts={len(lifts)}, capacities={capacity_values}")
        rate = main.findtext('Variables/Variable[Name="studentsPerMinutePerLift"]/Properties/InitialValue/Code')
        if rate is not None:
            print(f"  arrival_rate_per_lane={rate}/min")
    experiment = tree.find(EXPERIMENT)
    if experiment is not None:
        mode = experiment.findtext("RandomNumberGenerationType", "?")
        seed = experiment.findtext("SeedValue", "?")
        stop = experiment.findtext("ModelTimeProperties/StopOption", "?")
        end = experiment.findtext("ModelTimeProperties/FinalTime", "?")
        units = tree.findtext(MODEL + "/ModelTimeUnit", "?")
        print(f"  {mode}, seed_field={seed}; stop={stop}, final_time_field={end} {units}")


def verify_csv(path, cars):
    with path.open(encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        rows = list(reader)
    if tuple(reader.fieldnames or ()) != CSV_FIELDS or len(rows) != 1:
        raise ValueError("Expected one row with the lab output columns")
    row = rows[0]
    if None in row or any(value is None for value in row.values()):
        raise ValueError("CSV row does not match its header")
    time = float(row["time_s"])
    generated, boarded, transported, left, waiting, native = (
        int(row[key]) for key in ("generated", "boarded", "transported", "left", "active_waiting", "native_transported")
    )
    if not isfinite(time) or abs(time - 360.0) > 0.001 or not 0 < left <= generated or waiting < 0:
        raise ValueError("Invalid simulation time, source/sink counts or queue total")
    capacity = int(row["capacity"])
    rate = float(row["rate_per_lane"])
    peaks = [int(row[f"peak_load_{letter}"]) for letter in "abc"]
    if not isfinite(rate) or rate <= 0:
        raise ValueError("Invalid arrival rate")
    if cars:
        if not left <= transported == native <= boarded <= generated:
            raise ValueError("The elevator totals are inconsistent")
        if any(not 1 <= peak <= capacity for peak in peaks[:cars]) or any(peaks[cars:]):
            raise ValueError("Observed peak loads do not match the car count and capacity")
        for key in ("mean_wait_s", "mean_ride_s"):
            value = float(row[key])
            if not isfinite(value) or value < 0:
                raise ValueError(f"Invalid {key}")
        if float(row["mean_ride_s"]) <= 0:
            raise ValueError("Mean ride time should be positive")
    elif any((boarded, transported, native, waiting, capacity, *peaks, row["mean_wait_s"], row["mean_ride_s"])):
        raise ValueError("A walk-only run has no elevator data")
    print(f"{path.name}: t={time:g} s, generated={generated}, left={left}, transported={transported}")


def positive_number(value):
    number = float(value)
    if not isfinite(number) or number <= 0:
        raise argparse.ArgumentTypeError("Enter a finite number greater than zero")
    return number


def positive_int(value):
    number = int(value)
    if not 1 <= number <= 2**31 - 1:
        raise argparse.ArgumentTypeError("Capacity must fit a positive Java int")
    return number


def fixed_seed(value):
    number = int(value)
    if not -2**31 <= number <= 2**31 - 1:
        raise argparse.ArgumentTypeError("The lab accepts signed 32-bit seeds")
    return number


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subcommands = parser.add_subparsers(dest="command", required=True)
    create = subcommands.add_parser("create")
    create.add_argument("output", type=Path)
    create.add_argument("--cars", type=int, choices=(0, 1, 2, 3), required=True)
    create.add_argument("--capacity", type=positive_int, default=4)
    create.add_argument("--rate", type=positive_number, default=10.0, help="arrivals per minute per lane")
    create.add_argument("--seed", type=fixed_seed, default=42)
    starter = create.add_mutually_exclusive_group(required=True)
    starter.add_argument("--example", type=Path, help="Path to the installed Pedestrian Elevator.alp example")
    starter.add_argument("--seed-file", type=Path, help="Path to an existing local lab seed")
    configure = subcommands.add_parser("configure")
    configure.add_argument("input", type=Path)
    configure.add_argument("output", type=Path)
    configure.add_argument("--capacity", type=positive_int)
    configure.add_argument("--rate", type=positive_number)
    configure.add_argument("--seed", type=fixed_seed)
    structure = subcommands.add_parser("inspect")
    structure.add_argument("input", type=Path)
    csv_check = subcommands.add_parser("verify-csv")
    csv_check.add_argument("input", type=Path)
    csv_check.add_argument("--cars", type=int, choices=(0, 1, 2, 3), required=True)
    args = parser.parse_args()
    try:
        if args.command in ("create", "configure") and args.output.suffix.lower() != ".alp":
            raise ValueError("The output filename must end in .alp")
        if args.command == "create":
            tree = read_alp(args.example or args.seed_file)
            if args.example:
                from lab_seed import make_seed
                tree = make_seed(tree)
            make_lab(args.output.resolve(), args.cars, args.capacity, args.rate, args.seed, tree)
        elif args.command == "configure":
            tree = read_alp(args.input)
            apply_config(tree, args.capacity, args.rate, args.seed)
            rename_project(tree, args.output.stem)
            cars = len(tree.xpath("./Model/ActiveObjectClasses/ActiveObjectClass/Presentation/Level/Presentation/Elevator"))
            child(tree.find(EXPERIMENT), "AfterSimulationRunCode", metric_code(cars, args.output.resolve().with_suffix(".csv")))
            write_alp(tree, args.output)
            inspect(args.output)
        elif args.command == "inspect":
            inspect(args.input)
        else:
            verify_csv(args.input, args.cars)
    except (ValueError, OSError, xml.XMLSyntaxError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
